function norm(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/[’‘]/g, "'")
    .replace(/\s+/g, ' ')
}

export function tx(locale: KioskLocale, text?: string | null): string {
  if (!text) return ''
  if (locale !== 'sr') return text
  const key = norm(text)
  const exact = CONTENT_SR[key] ?? CONTENT_SR[key.replace(/[?!.]+$/, '').trim()]
  if (exact) return exact

  let out = text
  const replacements: Array<[RegExp, string]> = [
    [/\bLeft\b/g, 'Leva'],
    [/\bRight\b/g, 'Desna'],
    [/\bFront\b/g, 'prednja'],
    [/\bBack\b/g, 'zadnja'],
    [/\bUpper\b/g, 'gornja'],
    [/\bLower\b/g, 'donja'],
    [/\bHead\b/g, 'glava'],
    [/\bNeck\b/g, 'vrat'],
    [/\bShoulder\b/g, 'rame'],
    [/\bChest\b/g, 'grudi'],
    [/\bAbdomen\b/g, 'stomak'],
    [/\bHip\b/g, 'kuk'],
    [/\bGroin\b/g, 'prepone'],
    [/\bThigh\b/g, 'butina'],
    [/\bQuad\b/g, 'kvadriceps'],
    [/\bHamstring\b/g, 'zadnja loža'],
    [/\bKnee\b/g, 'koleno'],
    [/\bCalf\b/g, 'list'],
    [/\bShin\b/g, 'potkolenica'],
    [/\bAnkle\b/g, 'skočni zglob'],
    [/\bFoot\b/g, 'stopalo'],
    [/\bToe\b/g, 'prst'],
    [/\bArm\b/g, 'nadlaktica'],
    [/\bForearm\b/g, 'podlaktica'],
    [/\bElbow\b/g, 'lakat'],
    [/\bWrist\b/g, 'zglob'],
    [/\bHand\b/g, 'šaka'],
    [/\bFinger\b/g, 'prst'],
    [/\bTrap\b/g, 'trapez'],
    [/\bAdductor\b/g, 'aduktor'],
    [/\bGlute\b/g, 'gluteus'],
    [/\bIntercostal\b/g, 'interkostalni'],
  ]
  for (const [re, sr] of replacements) out = out.replace(re, sr)
  return out === text ? text : out
}

export function formatKioskDate(locale: KioskLocale, date = new Date()): string {
  return date.toLocaleDateString(locale === 'sr' ? 'sr-Latn-RS' : 'en-GB', {
    weekday: 'long',
    day: 'numeric',
    month: 'long',
  })
}
